export type UIKey = keyof (typeof ui)['es'];

// Reactive global lang state via Svelte 5 runes (.svelte.ts extension required)
let _lang = $state<Lang>(initialLang());

function initialLang(): Lang {
  if (typeof window === 'undefined') return 'es';
  try {
    const saved = localStorage.getItem('lang') as Lang | null;
    if (saved === 'es' || saved === 'en') return saved;
  } catch (_) {}
  const nav = navigator?.language ?? 'es';
  return nav.startsWith('en') ? 'en' : 'es';
}

export function getLang(): Lang {
  return _lang;
}
export function setLang(next: Lang): void {
  _lang = next;
  try {
    localStorage.setItem('lang', next);
  } catch (_) {}
  document.documentElement.lang = next === 'es' ? 'es-EC' : 'en-US';
}

export function t(key: UIKey): string {
  return (
    (ui[_lang] as Record<string, string>)[key] ?? (ui.es as Record<string, string>)[key] ?? key
  );
}

/**
 * Translate + interpolate `{name}` placeholders. Missing args render as empty string.
 * Used for keys with parameters: `firmar.step_of` ({n}), `firmar.step6.box_value` ({p,size,x,y}).
 */
export function tp(key: UIKey, params: Record<string, string | number>): string {
  const raw = t(key);
  return raw.replace(/\{(\w+)\}/g, (_, name) => {
    const v = params[name];
    return v === undefined || v === null ? '' : String(v);
  });
}
